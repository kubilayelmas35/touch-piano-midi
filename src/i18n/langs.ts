export const LANGUAGES = LANGUAGE_OPTIONS.map((o) => o.value);

export function isLanguage(v: unknown): v is Language {
  return typeof v === "string" && (LANGUAGES as string[]).includes(v);
}

export function localeTag(lang: Language): string {
  return LOCALE_TAG[lang] ?? "en-US";
}

export function isRtl(lang: Language): boolean {
  return lang === "ar" || lang === "he" || lang === "fa" || lang === "ur";
}

/** Videos only ship for tr/en; other UI languages fall back to English. */
export function videoLang(lang: Language): "tr" | "en" {
  return lang === "tr" ? "tr" : "en";
}

/** Built-in song titles: only Turkish has a dedicated title; others use English. */
export function songTitleLang(lang: Language): "tr" | "en" {
  return lang === "tr" ? "tr" : "en";
}
